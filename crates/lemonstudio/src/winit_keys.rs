/// A physical key.
pub fn physical(k: w::PhysicalKey) -> KeyCode {
    match k {
        w::PhysicalKey::Code(c) => code(c),
        w::PhysicalKey::Unidentified(_) => KeyCode::Unidentified,
    }
}

