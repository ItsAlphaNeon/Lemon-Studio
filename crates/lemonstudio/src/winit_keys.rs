/// A logical key.
pub fn key(k: &w::Key) -> Key {
    match k {
        w::Key::Named(n) => named(*n).map_or(Key::Unidentified, Key::Named),
        w::Key::Character(c) => Key::Character(c.to_string()),
        w::Key::Dead(c) => Key::Dead(*c),
        w::Key::Unidentified(_) => Key::Unidentified,
    }
}

