/// The key with this scancode (the plugin frames' keys).
pub fn scancode(s: u32) -> KeyCode {
    use winit::platform::scancode::PhysicalKeyExtScancode;
    physical(w::PhysicalKey::from_scancode(s))
}

/// The scancode of `c` (the X11 frames read the key map by them).
pub fn to_scancode(c: KeyCode) -> Option<u32> {
    use winit::platform::scancode::PhysicalKeyExtScancode;
    to_winit(c)?.to_scancode()
}

